"""Database access. Supabase (Postgres) when DATABASE_URL is set, otherwise a local SQLite file.

Both backends expose the same small interface used across the app:
    db.execute(sql, params) -> cursor with fetchone() / fetchall() / lastrowid, iterable
    db.lock(key)            -> serialise writes that allocate numbers (tokens, UHIDs)
Queries are written once with `?` placeholders.
"""
import json
import os
import re
import sqlite3
from datetime import datetime
from pathlib import Path

DATA_DIR = Path(os.environ.get("CLINIC_DATA_DIR", Path(__file__).resolve().parent.parent / "data"))
DB_PATH = DATA_DIR / "clinic.db"
UPLOAD_DIR = DATA_DIR / "uploads"
MIGRATIONS = Path(__file__).parent / "migrations"
DATABASE_URL = os.environ.get("DATABASE_URL", "").strip()


def is_postgres() -> bool:
    return DATABASE_URL.startswith(("postgres://", "postgresql://"))


# ---------- SQLite ----------

def _sqlite() -> sqlite3.Connection:
    DATA_DIR.mkdir(parents=True, exist_ok=True)
    conn = sqlite3.connect(DB_PATH, check_same_thread=False, timeout=15)
    conn.row_factory = sqlite3.Row
    conn.execute("pragma foreign_keys = on")
    conn.execute("pragma journal_mode = wal")
    return conn


class SqliteDB:
    dialect = "sqlite"

    def __init__(self):
        self.conn = _sqlite()

    def execute(self, sql, params=()):
        return self.conn.execute(sql, params)

    def script(self, sql):
        self.conn.executescript(sql)

    def lock(self, key):
        # A write transaction blocks other writers until commit, so reads that follow are race free.
        if not self.conn.in_transaction:
            self.conn.execute("begin immediate")

    def commit(self):
        self.conn.commit()

    def rollback(self):
        self.conn.rollback()

    def close(self):
        self.conn.close()


# ---------- Postgres (Supabase) ----------

class Row(dict):
    """dict that also answers row[0], like sqlite3.Row."""

    def __getitem__(self, k):
        if isinstance(k, int):
            return list(self.values())[k]
        return super().__getitem__(k)


def _row_factory(cursor):
    if cursor.description is None:
        return lambda values: None
    names = [c.name for c in cursor.description]
    return lambda values: Row(zip(names, values))


class PgCursor:
    def __init__(self, cur, lastrowid=None):
        self.cur, self.lastrowid = cur, lastrowid

    def fetchone(self):
        return self.cur.fetchone() if self.cur.description else None

    def fetchall(self):
        return self.cur.fetchall() if self.cur.description else []

    def __iter__(self):
        return iter(self.fetchall())


_INSERT = re.compile(r"^\s*insert\s+into\s+(\w+)", re.I)
_NO_ID = {"events", "schema_version", "sessions", "password_resets"}


def to_pg(sql: str) -> str:
    sql = re.sub(r"\bis not \?", "is distinct from ?", sql, flags=re.I)
    sql = sql.replace("%", "%%").replace("?", "%s")
    return sql


class PgDB:
    dialect = "postgres"

    def __init__(self):
        import psycopg
        self.conn = psycopg.connect(DATABASE_URL, row_factory=_row_factory, prepare_threshold=None)

    def execute(self, sql, params=()):
        m = _INSERT.match(sql)
        add_id = bool(m) and " returning " not in sql.lower() and m.group(1) not in _NO_ID
        cur = self.conn.cursor()
        cur.execute(to_pg(sql) + (" returning id" if add_id else ""), tuple(params))
        lastrowid = cur.fetchone()["id"] if add_id else None
        return PgCursor(cur, lastrowid)

    def script(self, sql):
        with self.conn.cursor() as cur:
            cur.execute(sql)

    def lock(self, key):
        self.conn.execute("select pg_advisory_xact_lock(hashtext(%s))", (str(key),))

    def commit(self):
        self.conn.commit()

    def rollback(self):
        self.conn.rollback()

    def close(self):
        self.conn.close()


def connect():
    return PgDB() if is_postgres() else SqliteDB()


# ---------- migrations ----------

def _dialect_sql(sql: str, dialect: str) -> str:
    if dialect == "postgres":
        sql = sql.replace("integer primary key", "bigint generated by default as identity primary key")
        sql = sql.replace("default current_timestamp", "default to_char(now() at time zone 'utc', 'YYYY-MM-DD HH24:MI:SS')")
    return sql


def migrate() -> None:
    """Apply app/migrations/NNN_name.sql in order, once each."""
    UPLOAD_DIR.mkdir(parents=True, exist_ok=True)
    db = connect()
    try:
        db.script("create table if not exists schema_version (version integer primary key, name text not null, applied_at text)")
        db.commit()
        done = {r[0] for r in db.execute("select version from schema_version").fetchall()}
        # Databases created before migrations existed already have the 001 tables.
        if not done:
            exists = db.execute(
                "select 1 from sqlite_master where type = 'table' and name = 'clinics'" if db.dialect == "sqlite"
                else "select 1 from information_schema.tables where table_name = 'clinics'").fetchone()
            if exists:
                db.execute("insert into schema_version (version, name, applied_at) values (1, '001_init', ?)", (now(),))
                db.commit()
                done = {1}
        for path in sorted(MIGRATIONS.glob("*.sql")):
            version = int(path.name.split("_", 1)[0])
            if version in done:
                continue
            db.script(_dialect_sql(path.read_text(), db.dialect))
            db.execute("insert into schema_version (version, name, applied_at) values (?, ?, ?)", (version, path.stem, now()))
            db.commit()
    finally:
        db.close()


def init() -> None:
    migrate()


def get_db():
    db = connect()
    try:
        yield db
        db.commit()
    except Exception:
        db.rollback()
        raise
    finally:
        db.close()


def row(r) -> dict | None:
    return dict(r) if r else None


def rows(rs) -> list[dict]:
    return [dict(r) for r in rs]


def now() -> str:
    return datetime.now().isoformat(timespec="seconds")


def log_event(db, clinic_id, actor_id, entity, entity_id, action, data=None) -> None:
    db.execute(
        "insert into events (clinic_id, actor_id, entity, entity_id, action, data, at) values (?, ?, ?, ?, ?, ?, ?)",
        (clinic_id, actor_id, entity, entity_id, action, json.dumps(data) if data else None, now()),
    )
